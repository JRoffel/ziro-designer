#!/usr/bin/env python3
"""
Extract KiCad's newstroke stroke-font table (`common/newstroke_font.cpp`, `newstroke_font[]`) into
`common/newstroke_font.ts`.

The table is one Hershey-encoded string per codepoint from U+0020, contiguous to U+FFEE: 65487
entries, 2.9 MB of source, most of it the CJK ideographs added in 2019. STROKE_FONT indexes it by
`codepoint - 0x20` and draws '?' past its end (stroke_font.cpp, GetTextAsGlyphs).

This writes the entries before the CJK blocks - U+0020..U+2FFF: Latin, Greek, Cyrillic, the
arrows, the mathematical operators, the box drawing and the rest of what a schematic carries -
which is what the bundle ships. Each entry's `/* U+XXXX */` comment is checked against its
position, so a gap or a reordering in the source fails here rather than shifting every glyph.

Run with the reference checkout present:

    python3 tools/kicad/extract_newstroke_font.py > common/newstroke_font.ts

The file is excluded from biome (biome.json): the strings are the C literals, escapes and all,
which are valid JavaScript as they stand.

It is committed as GENERATED DATA, with the generator beside it, because the reference tree is not
in this repo and CI cannot regenerate it.
"""
import pathlib
import re
import sys

REF = pathlib.Path('/home/akshay/kicad-reference')

# The first codepoint of CJK Radicals Supplement: the bundle stops before it.
FIRST_CJK = 0x3000

src = (REF / 'common/newstroke_font.cpp').read_text(encoding='utf-8')
start = src.index('const char* const newstroke_font[] =')
body = src[src.index('{', start) + 1 : src.index('};', start)]

entry = re.compile(r'"((?:[^"\\]|\\.)*)"\s*,?\s*(?:/\*\s*U\+([0-9A-Fa-f]+)[^*]*\*/)?')
glyphs = []

for m in entry.finditer(body):
    literal, comment = m.group(1), m.group(2)
    expected = 0x20 + len(glyphs)

    if comment is not None and int(comment, 16) != expected:
        sys.exit(f'entry {len(glyphs)}: its comment says U+{comment}, its position U+{expected:04X}')

    glyphs.append(literal)

if 0x20 + len(glyphs) <= FIRST_CJK:
    sys.exit(f'the table ends at U+{0x20 + len(glyphs) - 1:04X}, before U+{FIRST_CJK:04X}')

bundle = glyphs[: FIRST_CJK - 0x20]

print('''// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 ZiroEDA and contributors.
// Portions derived from KiCad, copyright The KiCad Developers. See NOTICE.md.
/**
 * KiCad Newstroke stroke-font glyph data, U+0020..U+2FFF: every block before the CJK ones.
 *
 * GENERATED by tools/kicad/extract_newstroke_font.py from KiCad common/newstroke_font.cpp
 * (GPL-2.0-or-later), verbatim. Each string is a Hershey-encoded glyph: the first char pair gives
 * the advance bounds (char - 'R'), then coordinate pairs, with ' R' marking a pen-up between
 * strokes. Entry i is codepoint 0x20 + i, as STROKE_FONT indexes it.
 *
 * The CJK blocks from U+3000 on are not here (~2.4 MB of the 2.9 MB table).
 */

/* eslint-disable */
export const NEWSTROKE_GLYPHS: readonly string[] = [''')
for g in bundle:
    print(f'  "{g}",')
print('];')
